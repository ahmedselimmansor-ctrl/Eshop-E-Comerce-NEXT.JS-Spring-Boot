package com.eshop.order.domain;

import com.eshop.common.domain.AuditableEntity;
import com.eshop.common.exception.BusinessException;
import com.eshop.common.exception.ErrorCode;
import com.eshop.common.money.Money;
import com.eshop.user.domain.User;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.annotations.BatchSize;
import org.hibernate.type.SqlTypes;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Set;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * A placed order - the system's financial record.
 *
 * <p>Everything here is a <b>snapshot</b>. The addresses are frozen JSON, the line items carry
 * their own copies of names, images, and prices, and the shipping method's name is duplicated onto
 * the row. None of it follows the catalog or the customer's address book afterwards.
 *
 * <p>That redundancy is the point. An invoice must say what was actually bought, at what price,
 * shipped where, on the day it was placed. If an order rendered by joining live catalog rows, then
 * renaming a product or correcting a typo in an address would silently rewrite history - including
 * documents already sent to a customer or a tax authority.
 */
@Entity
@Table(name = "orders")
@Getter
@Setter
@NoArgsConstructor
public class Order extends AuditableEntity {

    /** Human-facing reference, {@code EG-YYMMDD-NNNNN}. Generated by a database sequence. */
    @Column(name = "order_number", nullable = false, unique = true, length = 20)
    private String orderNumber;

    /** {@code null} for a guest checkout. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id")
    private User user;

    /*
     * `citext` in PostgreSQL, so uniqueness and lookups are case-insensitive without a
     * lower() index. Declared explicitly because Hibernate reads citext as an unknown type
     * and would otherwise refuse to validate the schema at startup.
     */
    @Column(name = "guest_email", columnDefinition = "citext")
    private String guestEmail;

    @Column(name = "guest_phone", length = 20)
    private String guestPhone;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 30)
    private OrderStatus status = OrderStatus.PENDING_PAYMENT;

    @Enumerated(EnumType.STRING)
    @Column(name = "payment_status", nullable = false, length = 30)
    private PaymentStatus paymentStatus = PaymentStatus.PENDING;

    @Enumerated(EnumType.STRING)
    @Column(name = "fulfillment_status", nullable = false, length = 30)
    private FulfillmentStatus fulfillmentStatus = FulfillmentStatus.UNFULFILLED;

    @Column(name = "currency", nullable = false, length = 3)
    private String currency = Money.DEFAULT_CURRENCY;

    @Column(name = "subtotal", nullable = false, precision = 12, scale = 2)
    private BigDecimal subtotal = BigDecimal.ZERO;

    @Column(name = "discount_total", nullable = false, precision = 12, scale = 2)
    private BigDecimal discountTotal = BigDecimal.ZERO;

    @Column(name = "tax_total", nullable = false, precision = 12, scale = 2)
    private BigDecimal taxTotal = BigDecimal.ZERO;

    @Column(name = "shipping_total", nullable = false, precision = 12, scale = 2)
    private BigDecimal shippingTotal = BigDecimal.ZERO;

    /** Cash-on-delivery surcharge, kept separate so it is visible on the invoice. */
    @Column(name = "cod_fee", nullable = false, precision = 12, scale = 2)
    private BigDecimal codFee = BigDecimal.ZERO;

    @Column(name = "grand_total", nullable = false, precision = 12, scale = 2)
    private BigDecimal grandTotal = BigDecimal.ZERO;

    @Column(name = "coupon_code", length = 40)
    private String couponCode;

    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "shipping_address", nullable = false, columnDefinition = "jsonb")
    private Map<String, Object> shippingAddress;

    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "billing_address", columnDefinition = "jsonb")
    private Map<String, Object> billingAddress;

    @Column(name = "shipping_method_id")
    private UUID shippingMethodId;

    @Column(name = "shipping_method_name_ar", length = 120)
    private String shippingMethodNameAr;

    @Column(name = "shipping_method_name_en", length = 120)
    private String shippingMethodNameEn;

    @Column(name = "customer_note")
    private String customerNote;

    /** Internal only - never included in any customer-facing response. */
    @Column(name = "admin_note")
    private String adminNote;

    @Column(name = "locale", nullable = false, length = 5)
    private String locale = "ar";

    // PostgreSQL `inet`. Bound from a plain String thanks to stringtype=unspecified on the
    // datasource URL; the columnDefinition is what lets schema validation recognise it.
    @Column(name = "ip", columnDefinition = "inet")
    private String ip;

    @Column(name = "user_agent")
    private String userAgent;

    @Column(name = "placed_at", nullable = false)
    private Instant placedAt = Instant.now();

    @Column(name = "paid_at")
    private Instant paidAt;

    @Column(name = "shipped_at")
    private Instant shippedAt;

    @Column(name = "delivered_at")
    private Instant deliveredAt;

    @Column(name = "cancelled_at")
    private Instant cancelledAt;

    @Column(name = "cancel_reason")
    private String cancelReason;

    @Version
    @Column(name = "version", nullable = false)
    private long version;

    /*
     * Left out of the paged entity graphs - Hibernate cannot page in SQL while a collection is
     * join-fetched. @BatchSize loads a whole page's worth in one extra query instead of one per row.
     */
    @BatchSize(size = 50)
    @OneToMany(mappedBy = "order", cascade = CascadeType.ALL, orphanRemoval = true, fetch = FetchType.LAZY)
    private List<OrderItem> items = new ArrayList<>();

    @OneToMany(mappedBy = "order", cascade = CascadeType.ALL, orphanRemoval = true, fetch = FetchType.LAZY)
    private Set<OrderStatusHistory> history = new LinkedHashSet<>();

    // ------------------------------------------------------------- behaviour --

    public boolean isGuestOrder() {
        return user == null;
    }

    public UUID customerId() {
        return user == null ? null : user.getId();
    }

    public String contactEmail() {
        return user != null ? user.getEmail() : guestEmail;
    }

    public String contactName() {
        if (user != null) {
            return user.fullName();
        }
        Object recipient = shippingAddress == null ? null : shippingAddress.get("recipientName");
        return recipient == null ? "" : String.valueOf(recipient);
    }

    /** Ownership check for {@code /me/orders/*}; guests match on the email they checked out with. */
    public boolean isVisibleTo(UUID userId, String email) {
        if (user != null) {
            return user.getId().equals(userId);
        }
        return guestEmail != null && guestEmail.equalsIgnoreCase(email);
    }

    public Money grandTotalMoney() {
        return Money.of(grandTotal, currency);
    }

    public Money subtotalMoney() {
        return Money.of(subtotal, currency);
    }

    public int totalQuantity() {
        return items.stream().mapToInt(OrderItem::getQuantity).sum();
    }

    public void addItem(OrderItem item) {
        item.setOrder(this);
        items.add(item);
    }

    /**
     * Moves the order to a new status, refusing illegal jumps and stamping the matching timestamp.
     *
     * @throws BusinessException {@code INVALID_STATUS_TRANSITION} when the move is not allowed
     */
    public void transitionTo(OrderStatus target, String note, UUID actorId,
                             OrderStatusHistory.ActorType actorType) {
        if (status == target) {
            return;
        }
        if (!status.canTransitionTo(target)) {
            throw new BusinessException(ErrorCode.INVALID_STATUS_TRANSITION,
                    "Cannot move order from " + status + " to " + target)
                    .withProperty("from", status.name())
                    .withProperty("to", target.name())
                    .withProperty("allowed", status.allowedTransitions().stream().map(Enum::name).toList());
        }

        OrderStatusHistory entry = new OrderStatusHistory();
        entry.setOrder(this);
        entry.setFromStatus(status);
        entry.setToStatus(target);
        entry.setNote(note);
        entry.setChangedBy(actorId);
        entry.setChangedByType(actorType);
        history.add(entry);

        status = target;
        Instant now = Instant.now();

        switch (target) {
            case PAID -> {
                paidAt = now;
                paymentStatus = PaymentStatus.PAID;
            }
            case SHIPPED -> shippedAt = now;
            case DELIVERED -> {
                deliveredAt = now;
                fulfillmentStatus = FulfillmentStatus.FULFILLED;
                // Cash on delivery settles at the doorstep, not at checkout.
                if (paymentStatus == PaymentStatus.PENDING) {
                    paymentStatus = PaymentStatus.PAID;
                    paidAt = now;
                }
            }
            case CANCELLED -> {
                cancelledAt = now;
                cancelReason = note;
            }
            case REFUNDED -> paymentStatus = PaymentStatus.REFUNDED;
            case PARTIALLY_REFUNDED -> paymentStatus = PaymentStatus.PARTIALLY_REFUNDED;
            default -> {
                // PENDING_PAYMENT, PROCESSING and FAILED carry no dedicated timestamp.
            }
        }
    }

    /** Recomputes {@code fulfillmentStatus} from what has actually been dispatched. */
    public void refreshFulfillmentStatus() {
        int total = items.stream().mapToInt(OrderItem::getQuantity).sum();
        int fulfilled = items.stream().mapToInt(OrderItem::getFulfilledQuantity).sum();

        fulfillmentStatus = fulfilled == 0
                ? FulfillmentStatus.UNFULFILLED
                : (fulfilled >= total ? FulfillmentStatus.FULFILLED : FulfillmentStatus.PARTIALLY_FULFILLED);
    }

    /** Amount still refundable: the captured total minus what has already been returned. */
    public Money refundableAmount(Money alreadyRefunded) {
        return grandTotalMoney().minus(alreadyRefunded).atLeastZero();
    }
}
